def require(ok, reason):
    if not ok:
        raise AssertionError(reason)

def command(argv, env=None, timeout=120, check=True):
    p=subprocess.run(argv, text=True, capture_output=True, timeout=timeout, env=env)
    if check and p.returncode:
        raise AssertionError("COMMAND_FAILED:"+str(argv[:3])+":"+
                             (p.stderr+p.stdout)[-1600:])
    return p

def grant():
    # TEST-ONLY signer generated by orchestrator; private key is never saved
    # or sent to the worker or the broker subprocess.
    key=Ed25519PrivateKey.generate()
    root=key.public_key().public_bytes(
        serialization.Encoding.Raw,serialization.PublicFormat.Raw)
    request=exact_request()
    now=datetime.now(timezone.utc)
    stmt={"profile":PROFILE,"request_sha256":sha(request),
          "source_sha256":SOURCE_SHA,"max_calls":1,
          "max_total_spend_micro_usd":0,"no_live_provider":True,
          "no_bank_effects":True,"nonce":secrets.token_hex(32),
          "issued_at":now.isoformat(),
          "expires_at":(now+timedelta(minutes=5)).isoformat()}
    signature=key.sign(canonical(stmt).encode()).hex()
    Ed25519PublicKey.from_public_bytes(root).verify(
        bytes.fromhex(signature),canonical(stmt).encode())
    return {"request":request,"approval":{"statement":stmt,"signature_hex":signature}},root

def inspect_worker(info,shared,worker):
    h=info["HostConfig"]; c=info["Config"]
    require(h["NetworkMode"]=="none" and h["ReadonlyRootfs"] is True and
            h["Privileged"] is False,"OS_NETWORK_ROOTFS_OR_PRIVILEGE_DRIFT")
    require({v.upper() for v in (h.get("CapDrop") or [])}=={"ALL"} and
            not h.get("CapAdd"),"WORKER_CAPABILITIES_MUST_BE_EMPTY")
    require(any("no-new-privileges" in z for z in (h.get("SecurityOpt") or [])),
            "NO_NEW_PRIVILEGES_REQUIRED")
    require(c["User"]=="65534:65534" and c["Cmd"]==["python","-B","/worker.py"],
            "UNTRUSTED_CONTAINER_IDENTITY_OR_ENTRYPOINT_DRIFT")
    require(not c.get("Entrypoint") and not h.get("PortBindings") and
            not h.get("Binds") and not h.get("Devices"),
            "ADDITIONAL_PRIVILEGED_CONTAINER_INTERFACE_FORBIDDEN")
    require(len(info.get("Mounts") or [])==2,
            "EXACT_TWO_READONLY_MOUNTS_REQUIRED")
    got={(str(m["Destination"]),str(Path(m["Source"]).resolve()),m["RW"])
         for m in info["Mounts"]}
    expected={("/ipc",str(shared.resolve()),False),
              ("/worker.py",str(worker.resolve()),False)}
    require(got==expected,"BROKER_PRIVATE_MATERIAL_OR_WRITABLE_MOUNT_DETECTED")
    env=c.get("Env") or []
    require(not any(z.startswith(("OPENAI_API_KEY=","OPENAI_BASE_URL=",
             "ANTHROPIC_API_KEY=","AWS_SECRET_ACCESS_KEY=",
             "GITHUB_TOKEN=","GH_TOKEN=")) for z in env),
             "WORKER_CREDENTIAL_ENV_FORBIDDEN")
    require(h.get("PidsLimit")==64 and
            0<h.get("Memory",0)<=268435456,
            "PIDS_AND_MEMORY_CAP_REQUIRED")

def ask_host(socket_path,envelope):
    raw=(json.dumps(envelope,sort_keys=True)+"\n").encode()
    with socket.socket(socket.AF_UNIX,socket.SOCK_STREAM) as s:
        s.settimeout(5)
        s.connect(str(socket_path))
        s.sendall(raw)
        return json.loads(s.recv(4096).decode().split("\n")[0])

def audit_sqlite(db_path,out):
    with sqlite3.connect(db_path) as db:
        require(db.execute("PRAGMA integrity_check").fetchone()[0]=="ok",
                "ORIGINAL_SQLITE_INTEGRITY_FAILURE")
        rows=db.execute("SELECT request_sha,approval_sha,state,claim_count,"
                        "response_sha,response_json FROM dispatches").fetchall()
        events=db.execute("SELECT event FROM audit ORDER BY seq").fetchall()
        with sqlite3.connect(out) as archive:
            db.backup(archive)
    require(len(rows)==1 and rows[0][2]=="MOCK_RECORDED" and
            rows[0][3]==1 and len(events)==2,
            "EXACTLY_ONE_DURABLE_MOCK_DISPATCH_REQUIRED")
    with sqlite3.connect(out) as copied:
        require(copied.execute("PRAGMA integrity_check").fetchone()[0]=="ok",
                "ARCHIVED_SQLITE_INTEGRITY_FAILURE")
    return {"request_sha256":rows[0][0],
            "approval_sha256":rows[0][1],
            "receipt_sha256":rows[0][4],
            "response_hash_matches":sha(json.loads(rows[0][5]))==rows[0][4],
            "events":[z[0] for z in events],
            "sqlite_archive_sha256":hashlib.sha256(out.read_bytes()).hexdigest()}

